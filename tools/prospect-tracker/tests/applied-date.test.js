import { test } from 'node:test';
import assert from 'node:assert/strict';
import { startFixture } from './fixtures/radar-server.js';
import { createClient } from '../vendor/supabase.js';
import { createRadarDataAccess, localCalendarDate, StaleProspectError } from '../data.js';
import { createStatusSaver } from '../status-save.js';

test('automatic Applied date, manual corrections, rollback, history and ordering through real SDK/PostgreSQL', async () => {
  const fixture = await startFixture();
  const client = createClient(fixture.origin, 'sb_publishable_synthetic', { auth: { persistSession: false, autoRefreshToken: false, detectSessionInUrl: false } });
  try {
    const { error } = await client.auth.signInWithPassword({ email: 'radar@example.invalid', password: 'fixture-only-password' });
    assert.equal(error, null);
    const data = createRadarDataAccess(client);
    const saveStatus = createStatusSaver(data, { canSave: () => true, busy: () => {} });
    const input = { company: 'Synthetic', title: 'Designer' };
    const id = () => crypto.randomUUID();
    let created = await data.createProspect({ ...input, id: id(), status: 'applied' });
    assert.equal(created.applied_on, localCalendarDate());
    assert.equal((await data.listStatusEvents(created.id)).length, 1);
    const manual = await data.createProspect({ ...input, id: id(), status: 'applied', applied_on: '2025-04-12' });
    assert.equal(manual.applied_on, '2025-04-12');
    let backdated = await data.createProspect({ ...input, id: id() });
    backdated = await data.updateProspect(backdated.id, { applied_on: '2025-05-10' }, backdated.updated_at);
    backdated = await saveStatus(backdated, 'applied');
    assert.equal(backdated.applied_on, '2025-05-10', 'a date entered before the transition is preserved');
    let prospect = await data.createProspect({ ...input, id: id() });
    await fetch(fixture.origin + '/__fixture/fail-next-save', { method: 'POST' });
    await assert.rejects(saveStatus(prospect, 'applied'), error => error.code === 'TEST_FAILURE');
    assert.equal((await data.getProspect(prospect.id)).status, 'prospect');
    assert.equal((await data.getProspect(prospect.id)).applied_on, null);
    assert.equal((await data.listStatusEvents(prospect.id)).length, 1);
    const stale = prospect;
    prospect = await data.updateProspect(prospect.id, { notes: 'Concurrent correction' }, prospect.updated_at);
    await assert.rejects(saveStatus(stale, 'applied'), StaleProspectError);
    assert.equal((await data.getProspect(prospect.id)).applied_on, null);
    prospect = await saveStatus(prospect, 'applied');
    assert.equal(prospect.applied_on, localCalendarDate());
    assert.equal((await data.listStatusEvents(prospect.id)).length, 2);
    prospect = await data.updateProspect(prospect.id, { applied_on: '2024-02-29' }, prospect.updated_at);
    assert.equal(prospect.status, 'applied');
    assert.equal((await data.listStatusEvents(prospect.id)).length, 2);
    prospect = await saveStatus(prospect, 'interviewing');
    assert.equal(prospect.applied_on, '2024-02-29');
    prospect = await saveStatus(prospect, 'applied');
    assert.equal(prospect.applied_on, '2024-02-29');
    assert.equal((await data.listStatusEvents(prospect.id)).length, 4);
    prospect = await data.updateProspect(prospect.id, { applied_on: null }, prospect.updated_at);
    prospect = await saveStatus(prospect, 'applied');
    assert.equal(prospect.applied_on, null, 'deliberately cleared date stays blank on unchanged status');
    assert.equal((await data.listStatusEvents(prospect.id)).length, 4);
    prospect = await data.updateProspect(prospect.id, { notes: 'Unrelated edit' }, prospect.updated_at);
    assert.equal(prospect.applied_on, null);
    const skipped = await data.createProspect({ ...input, id: id(), status: 'interviewing' });
    assert.equal(skipped.applied_on, null, 'later statuses do not imply an application');
    // Model a historical/imported record created before the enhancement, bypassing the new helper.
    const historical = await client.from('prospects').insert({ ...input, id: id(), status: 'applied' }).select('*').single();
    assert.equal(historical.error, null);
    assert.equal(historical.data.applied_on, null);
    let old = await data.updateProspect(historical.data.id, { notes: 'Historical record' }, historical.data.updated_at);
    old = await saveStatus(old, 'applied');
    assert.equal(old.applied_on, null);
    const before = (await data.listProspects()).filter(card => card.status === 'applied');
    await data.reorderColumn('applied', before.map(card => card.id), before.map(card => card.id).reverse());
    for (const card of before) assert.equal((await data.getProspect(card.id)).applied_on, card.applied_on);
    assert.equal((await data.listStatusEvents(old.id)).length, 1);
    created = await data.getProspect(created.id);
    assert.equal(created.applied_on, localCalendarDate(), 'reload keeps automatic date');
  } finally { await client.auth.signOut({ scope: 'local' }); await fixture.close(); }
});
